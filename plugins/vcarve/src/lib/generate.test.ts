import { describe, expect, it } from "vitest";

import { planCarve } from "./carve";
import { generateGcode } from "./generate";
import { boundsOf, buildShapes, type Ring } from "./geom";
import { check, defaultParams, type Params } from "./params";
import { report } from "./report";
import { parsePath } from "@shared/path";

const rect = (x0: number, y0: number, x1: number, y1: number): Ring => [{ x: x0, y: y0 }, { x: x1, y: y0 }, { x: x1, y: y1 }, { x: x0, y: y1 }];

const job = (patch: Partial<Params> = {}): Params => ({ ...defaultParams(), angle: 60, diameter: 12, tip: 0, maxDepth: 6, ...patch });
const strip = (g: string) => g.replace(/\([^)]*\)/g, "");

const make = (rings: Ring[], patch: Partial<Params> = {}) => {
	const p = job(patch);
	const c = check(p);
	const shapes = buildShapes(rings);
	const plan = planCarve(shapes, c.bit!, c.maxDepth ?? p.maxDepth!, p.quality);
	const bounds = boundsOf(rings);
	const gcode = plan.tooWide.length > 0 ? "" : generateGcode(p, plan, { bounds, description: "test" });
	return { p, plan, bounds, gcode };
};

describe("G-code", () => {
	it("uses the same safe words and layout as the other plugins", () => {
		const { gcode } = make([rect(0, 0, 40, 6)]);
		const words = new Set([...strip(gcode).matchAll(/\b([GM]\d+)\b/g)].map((m) => m[1]));
		for (const w of words) expect(["G0", "G1", "G4", "G17", "G21", "G90", "G94", "M3", "M5", "M30"]).toContain(w);
		expect(gcode).toMatch(/^\(Generated by V-Carve - gSender plugin\)$/m);
		expect(gcode).toMatch(/^G21$/m);
		expect(gcode.trim().split("\n").slice(-2)).toEqual(["M5", "M30"]);
	});

	it("never goes below the maximum depth, whatever the limit", () => {
		for (const maxDepth of [6, 8, 10]) {
			const { gcode } = make([rect(0, 0, 40, 6)], { maxDepth });
			for (const s of parsePath(gcode)) expect(s.to.z).toBeGreaterThanOrEqual(-maxDepth - 1e-9);
		}
	});

	it("when the artwork is too wide for the limit it makes no G-code at all", () => {
		for (const maxDepth of [1, 2.5]) {
			const p = job({ maxDepth });
			const c = check(p);
			const rings = [rect(0, 0, 40, 6)];
			const plan = planCarve(buildShapes(rings), c.bit!, c.maxDepth!, p.quality);
			// The planner still keeps every point within the limit...
			expect(plan.tooWide.length).toBeGreaterThan(0);
			for (const ch of plan.chains) for (const q of ch) expect(q.z).toBeGreaterThanOrEqual(-maxDepth);
			// ...and the writer refuses to write it.
			expect(() => generateGcode(p, plan, { bounds: boundsOf(rings), description: "x" })).toThrow(/too wide/);
		}
	});

	it("is the same job in inches, with four decimals", () => {
		const mm = parsePath(make([rect(0, 0, 40, 6)]).gcode);
		const inch = make([rect(0, 0, 40, 6)], { units: "in" }).gcode;
		expect(inch).toMatch(/^G20$/m);
		expect(inch).toMatch(/\.\d{4}\b/);
		const segs = parsePath(inch);
		expect(segs).toHaveLength(mm.length);
		segs.forEach((s, i) => {
			expect(s.to.x * 25.4).toBeCloseTo(mm[i].to.x, 2);
			expect(s.to.z * 25.4).toBeCloseTo(mm[i].to.z, 2);
		});
	});

	it("cuts start by ramping in from the surface, or plunge at the plunge rate", () => {
		const { gcode } = make([rect(0, 0, 40, 6)]);
		// A bar's cuts all start at a sharp corner at the surface.
		expect(gcode).toMatch(/^G1 Z0 F300$/m);
		expect(gcode).toMatch(/^G0 Z1$/m);
	});

	it("raises the bit between cuts", () => {
		const { gcode, plan } = make([rect(0, 0, 40, 6), rect(60, 0, 100, 6)]);
		expect(plan.chains.length).toBeGreaterThan(1);
		expect(gcode.match(/^G0 Z1$/gm)!.length).toBe(plan.chains.length);
	});

	it("work zero follows the chosen spot on the artwork", () => {
		const lowerLeft = parsePath(make([rect(10, 20, 50, 26)]).gcode).filter((s) => s.kind === "line");
		expect(Math.min(...lowerLeft.map((s) => s.to.x))).toBeCloseTo(0, 6);
		expect(Math.min(...lowerLeft.map((s) => s.to.y))).toBeCloseTo(0, 6);
		const centre = parsePath(make([rect(10, 20, 50, 26)], { origin: "center" }).gcode).filter((s) => s.kind === "line");
		expect(Math.min(...centre.map((s) => s.to.x))).toBeCloseTo(-20, 6);
		expect(Math.max(...centre.map((s) => s.to.y))).toBeCloseTo(3, 6);
		const upperRight = parsePath(make([rect(10, 20, 50, 26)], { origin: "upper-right" }).gcode).filter((s) => s.kind === "line");
		expect(Math.max(...upperRight.map((s) => s.to.x))).toBeCloseTo(0, 6);
		expect(Math.max(...upperRight.map((s) => s.to.y))).toBeCloseTo(0, 6);
	});

	it("refuses to write a cut that is too deep", () => {
		const { p, plan, bounds } = make([rect(0, 0, 40, 6)]);
		const bad = { ...plan, chains: [[{ x: 0, y: 0, z: -9 }, { x: 1, y: 0, z: -9 }]] };
		expect(() => generateGcode(p, bad, { bounds, description: "x" })).toThrow(/deeper than the maximum/);
	});
});

describe("report", () => {
	const wide = [rect(0, 0, 40, 20)];
	it("too wide is a warning, not an error: it says where, by how much, how many, and that nothing was made", () => {
		const { p, plan, bounds } = make(wide);
		const r = report(p, plan, bounds);
		expect(r.errors).toEqual([]);
		expect(r.blocked).toBe(true);
		expect(r.warnings).toHaveLength(1);
		const w = r.warnings[0];
		expect(w).toMatch(/too wide for this bit at 6 mm deep, in \d+ place/);
		expect(w).toMatch(/no G-code was made/);
		expect(w).toMatch(/X\d+(\.\d)? Y\d+(\.\d)?/);
		expect(w).toMatch(/17\.32 mm depth/);
		expect(w).toMatch(/11\.32 mm more than allowed/);
		expect(w).toMatch(/red circles/);
		expect(w).not.toMatch(/Cap the depth/);
	});
	it("counts the places", () => {
		const { p, plan, bounds } = make([rect(0, 0, 40, 20), rect(100, 0, 140, 20)]);
		expect(report(p, plan, bounds).warnings[0]).toMatch(/in 2 places/);
	});
	it("warns about parts thinner than the tip", () => {
		const { p, plan, bounds } = make([rect(0, 0, 40, 0.3)], { tip: 0.5 });
		const r = report(p, plan, bounds);
		expect(r.warnings.join(" ")).toMatch(/narrower than the bit's tip \(0\.5 mm\)/);
		expect(r.warnings.join(" ")).toMatch(/can't be cut to a point/);
		expect(r.errors.join(" ")).toMatch(/Nothing can be cut/);
		expect(r.blocked).toBe(true);
	});
	it("a fine job has nothing to report and is not blocked", () => {
		const { p, plan, bounds } = make([rect(0, 0, 40, 6)]);
		expect(report(p, plan, bounds)).toEqual({ errors: [], warnings: [], blocked: false });
	});
	it("speaks in inches when the job is in inches", () => {
		const { p, plan, bounds } = make(wide, { units: "in" });
		expect(report(p, plan, bounds).warnings[0]).toMatch(/ in /);
	});
});

describe("check: bit and depth values", () => {
	const msg = (patch: Partial<Params>) => check({ ...job(), ...patch }).errors.join(" | ");
	it("a fresh form has a usable bit already, and the depth is worked out from it", () => {
		const c = check(defaultParams());
		expect(c.errors).toEqual([]);
		expect(c.missing).toEqual([]);
		expect(c.bit).toEqual({ angle: 60, diameter: 12.7, tip: 0, cuttingLength: null });
		// A 60° bit 12.7 mm wide cuts 6.35 / tan(30°) = 11 mm deep at most, and that is the automatic limit.
		expect(c.deepest).toBeCloseTo(6.35 / Math.tan(Math.PI / 6), 9);
		expect(c.maxDepth).toBe(c.deepest);
		expect(defaultParams().maxDepth).toBeNull();
	});
	it("the automatic depth follows the bit: angle, diameter, tip and cutting length", () => {
		const auto = (patch: Partial<Params>) => check({ ...defaultParams(), ...patch }).maxDepth!;
		expect(auto({ angle: 90 })).toBeCloseTo(6.35, 9);
		expect(auto({ diameter: 6 })).toBeCloseTo(3 / Math.tan(Math.PI / 6), 9);
		expect(auto({ tip: 2 })).toBeCloseTo(5.35 / Math.tan(Math.PI / 6), 9);
		expect(auto({ cuttingLength: 4 })).toBe(4);
	});
	it("a smaller limit can still be entered, and is used instead", () => {
		const c = check({ ...defaultParams(), maxDepth: 5 });
		expect(c.errors).toEqual([]);
		expect(c.maxDepth).toBe(5);
	});
	it("clearing a box asks for it by name, and nothing can be made until it is back", () => {
		for (const [patch, word] of [[{ angle: null }, /included angle/], [{ diameter: null }, /maximum diameter/], [{ tip: null }, /tip diameter/]] as const) {
			const c = check({ ...defaultParams(), ...patch });
			expect(c.missing.join(" ")).toMatch(word);
			expect(c.errors).toEqual([]);
			expect(c.bit).toBeNull();
			expect(c.maxDepth).toBeNull();
		}
	});
	it("an angle outside 1 to 179 is refused", () => {
		for (const angle of [0, 0.5, 180, 200, -10]) expect(msg({ angle })).toMatch(/between 1° and 179°/);
		for (const angle of [1, 60, 90, 179]) expect(msg({ angle })).not.toMatch(/included angle|between 1°/);
	});
	it("a tip as wide as, or wider than, the bit is refused", () => {
		expect(msg({ tip: 12 })).toMatch(/can't be as wide as the whole bit/);
		expect(msg({ tip: 20 })).toMatch(/can't be as wide as the whole bit/);
		expect(msg({ tip: -1 })).toMatch(/can't be negative/);
		expect(msg({ tip: 0 })).not.toMatch(/tip/);
	});
	it("a zero or negative diameter is refused", () => {
		expect(msg({ diameter: 0 })).toMatch(/diameter must be greater than 0/);
		expect(msg({ diameter: -3 })).toMatch(/diameter must be greater than 0/);
	});
	it("a depth deeper than the bit can cut is refused, showing the deepest allowed", () => {
		// A 60° bit 12 mm wide cuts 6 / tan(30°) = 10.39 mm deep at most.
		const c = check(job({ maxDepth: 12 }));
		expect(c.errors.join(" ")).toMatch(/deeper than this bit can cut/);
		expect(c.errors.join(" ")).toMatch(/10\.39 mm/);
		expect(c.errors.join(" ")).toMatch(/leave it empty for automatic/);
		expect(c.maxDepth).toBeNull();
		expect(check(job({ maxDepth: 10 })).errors).toHaveLength(0);
	});
	it("the cutting length can be the limit", () => {
		const c = check(job({ cuttingLength: 8, maxDepth: 9 }));
		expect(c.errors.join(" ")).toMatch(/8 mm, where its cutting edge ends/);
		expect(check(job({ cuttingLength: 8, maxDepth: 8 })).errors).toHaveLength(0);
		expect(check(job({ cuttingLength: -2 })).errors.join(" ")).toMatch(/cutting length must be greater than 0/);
	});
	it("a tip makes the bit reach less deep", () => {
		// With a 2 mm tip: (12 - 2) / 2 / tan(30°) = 8.66 mm.
		expect(check(job({ tip: 2 })).deepest).toBeCloseTo(8.66, 2);
	});
	it("a valid bit and depth give a usable result", () => {
		const c = check(job());
		expect(c.errors).toHaveLength(0);
		expect(c.bit).toEqual({ angle: 60, diameter: 12, tip: 0, cuttingLength: null });
		expect(c.maxDepth).toBe(6);
	});
	it("rejects a bad feed, and asks for text when there is none", () => {
		expect(msg({ feedrate: 0 })).toMatch(/feed rate/);
		expect(check({ ...job(), text: "   " }).missing.join(" ")).toMatch(/Type the text/);
	});
});
