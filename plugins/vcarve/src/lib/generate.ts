/**
 * V-Carve → GRBL G-code. Straight G0/G1 moves in the same style as the other plugins.
 *
 * The bit follows each cut chain: it rapids to the start at a low height, then goes down to the
 * start of the cut (a ramp from the surface where the cut begins at a sharp point, a plunge
 * where it has to start deep) and follows the centre line with the depth changing as it goes.
 * Nothing is ever cut deeper than the maximum depth, and a chain that would be is refused.
 *
 * With roughing, the roughing cuts come first at the cutting feed, then the finishing cuts at a
 * percentage of it.
 *
 * Work zero: X0 Y0 is the chosen corner or centre of the artwork's bounding box, Z0 is the top
 * of the stock.
 */

import { comment, fmt } from "@shared/gcode";
import { originOffset, POSITION_NAMES } from "@shared/position";
import { MM_PER_INCH } from "@shared/units";

import type { CarvePlan } from "./carve";
import type { Bounds } from "./geom";
import type { Params } from "./params";

export type Artwork = { bounds: Bounds; description: string };

/** Moves a point from artwork coordinates to machine coordinates, so X0 Y0 is where the user chose. */
export const toMachine = (p: Params, bounds: Bounds) => {
	const w = bounds.maxX - bounds.minX;
	const h = bounds.maxY - bounds.minY;
	const o = originOffset(p.origin, w, h);
	return (x: number, y: number) => ({ x: x - bounds.minX - o.x, y: y - bounds.minY - o.y });
};

export const generateGcode = (p: Params, plan: CarvePlan, art: Artwork, warnings: string[] = []): string => {
	const inch = p.units === "in";
	const scale = inch ? 1 / MM_PER_INCH : 1;
	const dec = inch ? 4 : 3;
	const c = (v: number) => fmt(v * scale, dec);
	const f = (v: number) => fmt(v * scale, inch ? 2 : 0);
	// Too wide for the bit at the allowed depth: nothing is generated, whatever the caller asks.
	if (plan.tooWide.length > 0) throw new Error("The artwork is too wide for this bit at the allowed depth, so no G-code can be generated.");
	const shift = toMachine(p, art.bounds);
	const clearance = Math.min(1, p.safeZ);

	const out: string[] = [];
	out.push(comment("Generated by V-Carve - gSender plugin"));
	out.push(comment(`Units: ${p.units}`));
	out.push(comment(`Artwork: ${art.description}, ${fmt(art.bounds.maxX - art.bounds.minX, 2)} x ${fmt(art.bounds.maxY - art.bounds.minY, 2)} mm`));
	out.push(comment(`Bit: ${fmt(p.angle ?? 0, 1)} degree V, ${fmt(p.diameter ?? 0, 3)} mm wide, ${fmt(p.tip ?? 0, 3)} mm tip`));
	out.push(comment(`Deepest cut: ${fmt(Math.min(plan.deepestNeeded, plan.maxDepth), 3)} mm (limit ${fmt(plan.maxDepth, 3)} mm)`));
	out.push(comment(`Feeds: cut ${fmt(p.feedrate, 0)}, plunge ${fmt(p.plungeRate, 0)} mm/min, spindle ${fmt(p.spindleRpm, 0)} RPM`));
	if (plan.passes) {
		out.push(comment(`Roughing pass leaves ${fmt(plan.passes.allowance, 3)} mm on each wall, then a finishing pass at ${fmt(p.finishFeedPercent, 0)}% of the cutting feed, ${fmt(p.feedrate * (p.finishFeedPercent / 100), 0)} mm/min`));
	}
	out.push(comment(`Work zero: ${POSITION_NAMES[p.origin]} of the artwork, Z0 = top of stock`));
	for (const w of warnings) out.push(comment(`WARNING: ${w}`));

	out.push(inch ? "G20" : "G21", "G90", "G17", "G94");
	out.push(`M3 S${fmt(p.spindleRpm, 0)}`);
	if (p.spindleDwell > 0) out.push(`G4 P${fmt(p.spindleDwell, 2)}`);
	out.push(`G0 Z${c(p.safeZ)}`);

	let lastF = 0;
	const roughCount = plan.passes?.roughing ?? 0;
	plan.chains.forEach((chain, i) => {
		const finishing = plan.passes !== null && i >= roughCount;
		const cutFeed = finishing ? p.feedrate * (p.finishFeedPercent / 100) : p.feedrate;
		for (const pt of chain) {
			// Never trust the plan: refuse anything past the limit rather than cut it.
			if (pt.z < -plan.maxDepth - 1e-9) throw new Error("A cut would go deeper than the maximum depth.");
		}
		const start = shift(chain[0].x, chain[0].y);
		out.push(
			comment(
				plan.passes
					? finishing
						? `Finishing cut ${i - roughCount + 1} of ${plan.passes.finishing}`
						: `Roughing cut ${i + 1} of ${roughCount}`
					: `Cut ${i + 1} of ${plan.chains.length}`,
			),
		);
		out.push(`G0 Z${c(clearance)}`);
		out.push(`G0 X${c(start.x)} Y${c(start.y)}`);
		out.push(`G1 Z${c(chain[0].z)} F${f(p.plungeRate)}`);
		lastF = p.plungeRate;
		let last = chain[0];
		for (let k = 1; k < chain.length; k += 1) {
			const q = chain[k];
			const m = shift(q.x, q.y);
			const same = Math.abs(q.x - last.x) < 1e-9 && Math.abs(q.y - last.y) < 1e-9;
			if (same && Math.abs(q.z - last.z) < 1e-9) continue;
			// A vertical move is a plunge; everything else is a cut.
			const rate = same ? p.plungeRate : cutFeed;
			out.push(`G1${same ? "" : ` X${c(m.x)} Y${c(m.y)}`} Z${c(q.z)}${rate !== lastF ? ` F${f(rate)}` : ""}`);
			lastF = rate;
			last = q;
		}
	});
	out.push(`G0 Z${c(p.safeZ)}`, "M5", "M30");
	return `${out.join("\n")}\n`;
};
