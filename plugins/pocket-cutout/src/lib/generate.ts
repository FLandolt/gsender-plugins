/**
 * Pocket Cutout → GRBL G-code.
 *
 * G0/G1 moves, plus G2/G3 for circles and rounded corners unless arcs are switched off
 * (then they are short G1 chords). No canned cycles, no cutter compensation.
 *
 * The pocket is cut in levels of at most the stepdown. Each level starts at the middle
 * with a helical ramp (never a plunge into material) and is then cleared in a spiral
 * from the middle outwards, ending on the wall (see geometry.ts). The tool never leaves
 * the pocket: the path stays one tool radius inside.
 *
 * Work zero is the centre of the pocket or any corner of its bounding box; Z0 is the
 * stock top.
 */

import { arcMove, comment, fmt } from "@shared/gcode";
import { originOffset, POSITION_NAMES } from "@shared/position";
import { MM_PER_INCH } from "@shared/units";

import { levelSegs, toolRegion, zLevels } from "./geometry";
import type { Params } from "./params";

export const generateGcode = (p: Params): string => {
	const inch = p.units === "in";
	const scale = inch ? 1 / MM_PER_INCH : 1;
	const dec = inch ? 4 : 3;
	const c = (v: number) => fmt(v * scale, dec);
	const f = (v: number) => fmt(v * scale, inch ? 2 : 0);
	const nf = { scale, decimals: dec };

	const round = p.shape === "circle";
	const bw = round ? p.diameter : p.width;
	const bh = round ? p.diameter : p.height;
	// Shift from pocket-centred to machine coordinates.
	const origin = originOffset(p.origin, bw, bh);
	const dx = bw / 2 - origin.x;
	const dy = bh / 2 - origin.y;

	const region = toolRegion(p);
	const levels = zLevels(p.depth, p.stepdown);
	const clearance = Math.min(1, p.safeZ);

	const out: string[] = [];
	out.push(comment("Generated by Pocket Cutout - gSender plugin"));
	out.push(comment(`Units: ${p.units}`));
	out.push(comment(round
		? `Pocket: circle, diameter ${fmt(p.diameter, 3)} mm, depth ${fmt(p.depth, 3)} mm in ${levels.length} level(s)`
		: `Pocket: ${fmt(p.width, 3)} x ${fmt(p.height, 3)} mm, corner radius ${fmt(p.cornerRadius, 3)} mm, depth ${fmt(p.depth, 3)} mm in ${levels.length} level(s)`));
	out.push(comment(`Tool: endmill ${fmt(p.toolDiameter, 3)} mm, stepover ${fmt(p.toolDiameter * p.stepover, 3)} mm`));
	out.push(comment(`Clearing: spiral from the middle outwards, ${p.rotation === "cw" ? "clockwise (climb)" : "counter-clockwise (conventional)"}, entering with a helix`));
	out.push(comment(`Feeds: cut ${fmt(p.feedrate, 0)}, plunge ${fmt(p.plungeRate, 0)} mm/min, spindle ${fmt(p.spindleRpm, 0)} RPM`));
	out.push(comment(`Work zero: ${POSITION_NAMES[p.origin]} of the pocket${round ? "'s bounding square" : ""}, Z0 = top of stock`));

	out.push(inch ? "G20" : "G21", "G90", "G17", "G94");
	out.push(`M3 S${fmt(p.spindleRpm, 0)}`);
	if (p.spindleDwell > 0) out.push(`G4 P${fmt(p.spindleDwell, 2)}`);
	out.push(`G0 Z${c(p.safeZ)}`);

	let last = { x: Number.NaN, y: Number.NaN, z: 0 };
	let lastF = 0;
	let planeSet = false;
	let zPrev = 0;
	levels.forEach((z, li) => {
		const { start, segs } = levelSegs(p, region, zPrev, z);
		out.push(comment(`Level ${li + 1} of ${levels.length}, Z${c(z)}`));
		out.push(`G0 Z${c(clearance)}`);
		out.push(`G0 X${c(start.x + dx)} Y${c(start.y + dy)}`);
		// Just above the surface the last level left, then onto it; the ramp does the cutting.
		out.push(`G0 Z${c(Math.min(clearance, zPrev + 1))}`);
		out.push(`G1 Z${c(zPrev)} F${f(p.plungeRate)}`);
		last = { x: start.x + dx, y: start.y + dy, z: zPrev };
		lastF = p.plungeRate;

		for (const s of segs) {
			const x = s.x + dx;
			const y = s.y + dy;
			const zChanged = Math.abs(s.z - last.z) >= 1e-9;
			if (s.arc) {
				if (!planeSet) {
					out.push("G17");
					planeSet = true;
				}
				const word = arcMove(nf, {
					from: last,
					centre: { x: s.arc.cx + dx, y: s.arc.cy + dy },
					to: { x, y },
					z: zChanged ? s.z : undefined,
					cw: s.arc.cw,
				});
				out.push(`${word}${p.feedrate !== lastF ? ` F${f(p.feedrate)}` : ""}`);
				lastF = p.feedrate;
			} else {
				const sameXY = Math.abs(x - last.x) < 1e-9 && Math.abs(y - last.y) < 1e-9;
				if (sameXY && !zChanged) continue;
				const rate = sameXY ? p.plungeRate : p.feedrate;
				out.push(`G1${sameXY ? "" : ` X${c(x)} Y${c(y)}`}${zChanged ? ` Z${c(s.z)}` : ""}${rate !== lastF ? ` F${f(rate)}` : ""}`);
				lastF = rate;
			}
			last = { x, y, z: s.z };
		}
		zPrev = z;
	});

	out.push(`G0 Z${c(p.safeZ)}`, "M5", "M30");
	return `${out.join("\n")}\n`;
};
