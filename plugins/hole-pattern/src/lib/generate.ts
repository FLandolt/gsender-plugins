/**
 * Hole Pattern → GRBL G-code.
 *
 * Deliberately restricted to what GRBL 1.1 parses: G0/G1 linear moves and, unless
 * switched off, G2/G3 arcs with IJ centre offsets. No canned cycles. With arcs off,
 * circles are written as short chords.
 *
 * Work zero: X0 Y0 is the centre of the first hole, in the chosen corner of the grid
 * (lower-left by default), Z0 is the top of the stock. Further holes extend away from
 * that corner: +X and +Y from a lower-left zero, -X from a right one, -Y from an upper one.
 *
 * Holes are cut one after another. Each hole is cut level by level (`stepdown`):
 * at the hole centre the bit spirals down in a small helix to the level's
 * depth, spirals outward (flat) until it reaches the wall, runs one full circle
 * on the wall, then returns to the centre and repeats for the next level.
 * A hole exactly as wide as the tool can't spiral, so it is peck-plunged.
 *
 * With arcs on, the helix and the wall circle are full G3 circles, each written as
 * two half-circle arcs (the helix one descends as it goes) and the outward spiral is a chain of quarter-turn arcs, each
 * the circle through three points of the true spiral, so the radius grows step by step.
 */

import { arcMove, circleMoves, comment, fmt, type Pt } from "@shared/gcode";
import { POSITION_NAMES } from "@shared/position";
import { MM_PER_INCH } from "@shared/units";

import type { Params } from "./params";

export type Point = { x: number; y: number };

export const holeCentres = (p: Params): Point[] => {
	const sx = p.origin.endsWith("right") ? -1 : 1;
	const sy = p.origin.startsWith("upper") ? -1 : 1;
	const out: Point[] = [];
	for (let j = 0; j < p.countY; j += 1) {
		// Serpentine order keeps rapid travel short.
		for (let k = 0; k < p.countX; k += 1) {
			const i = j % 2 === 0 ? k : p.countX - 1 - k;
			// `+ 0` turns a mirrored -0 into 0.
			out.push({ x: sx * i * p.spacingX + 0, y: sy * j * p.spacingY + 0 });
		}
	}
	return out;
};

/** Cumulative depths for each cutting level, ending exactly at `depth`. */
export const zLevels = (depth: number, stepdown: number): number[] => {
	const n = Math.max(1, Math.ceil(depth / stepdown - 1e-9));
	return Array.from({ length: n }, (_, i) => -Math.min(depth, (i + 1) * (depth / n)));
};

/** Chord count so the polygon's sag stays under ~0.01 mm. */
const segmentsFor = (r: number): number => {
	const sag = 0.01;
	const n = Math.ceil(Math.PI / Math.acos(Math.max(0, 1 - sag / Math.max(r, sag))));
	return Math.min(360, Math.max(24, n));
};

/** Centre of the circle through three points (not in a line). */
const circumcentre = (a: Pt, b: Pt, c: Pt): Pt => {
	const d = 2 * (a.x * (b.y - c.y) + b.x * (c.y - a.y) + c.x * (a.y - b.y));
	const a2 = a.x * a.x + a.y * a.y, b2 = b.x * b.x + b.y * b.y, c2 = c.x * c.x + c.y * c.y;
	return {
		x: (a2 * (b.y - c.y) + b2 * (c.y - a.y) + c2 * (a.y - b.y)) / d,
		y: (a2 * (c.x - b.x) + b2 * (a.x - c.x) + c2 * (b.x - a.x)) / d,
	};
};

export const generateGcode = (p: Params): string => {
	const inch = p.units === "in";
	const scale = inch ? 1 / MM_PER_INCH : 1;
	const dec = inch ? 4 : 3;
	const c = (v: number) => fmt(v * scale, dec);
	const f = (v: number) => fmt(v * scale, inch ? 2 : 0);

	const centres = holeCentres(p);
	const levels = zLevels(p.depth, p.stepdown);
	const wall = Math.max(0, (p.holeDiameter - p.toolDiameter) / 2);
	const step = p.toolDiameter * p.stepover;
	// Radius of the helix in the middle: the bit's centre travels on a circle 3/4 of the
	// tool diameter wide. Wider is gentler, but it must stay under the tool radius so
	// no core is left standing in the middle.
	const rh = Math.min(wall, p.toolDiameter * 0.375);
	// Arcs smaller than this can't be printed reliably at 3 decimals.
	const arcs = p.useArcs && rh >= 0.01;
	const nf = { scale, decimals: dec };

	const out: string[] = [];
	out.push(comment("Generated by Hole Pattern - gSender plugin"));
	out.push(comment(`Units: ${p.units}`));
	out.push(comment(`Holes: ${p.countX} x ${p.countY} = ${centres.length}, dia ${fmt(p.holeDiameter, 3)} mm, depth ${fmt(p.depth, 3)} mm`));
	out.push(comment(`Pitch: ${fmt(p.spacingX, 3)} x ${fmt(p.spacingY, 3)} mm`));
	out.push(comment(`Tool: endmill ${fmt(p.toolDiameter, 3)} mm`));
	out.push(comment(`Feeds: cut ${fmt(p.feedrate, 0)}, plunge ${fmt(p.plungeRate, 0)} mm/min, spindle ${fmt(p.spindleRpm, 0)} RPM`));
	out.push(comment(`Work zero: centre of the ${p.countX * p.countY > 1 ? `${POSITION_NAMES[p.origin].replace(" corner", "")} hole` : "hole"} (X0 Y0), Z0 = top of stock`));

	out.push(inch ? "G20" : "G21", "G90", "G17", "G94");
	out.push(`M3 S${fmt(p.spindleRpm, 0)}`);
	if (p.spindleDwell > 0) out.push(`G4 P${fmt(p.spindleDwell, 2)}`);
	out.push(`G0 Z${c(p.safeZ)}`);

	centres.forEach((h, idx) => {
		out.push(comment(`Hole ${idx + 1} of ${centres.length}`));
		out.push(`G0 X${c(h.x)} Y${c(h.y)}`);
		if (wall <= 1e-6) {
			// Tool-sized hole: peck-plunge at the centre.
			for (const z of levels) {
				out.push(`G1 Z${c(z)} F${f(p.plungeRate)}`);
				if (z !== levels[levels.length - 1]) out.push(`G0 Z${c(z + Math.min(1, p.stepdown))}`);
			}
		}
		else {
			out.push(`G0 X${c(h.x + rh)} Y${c(h.y)}`);
			out.push(`G0 Z${c(Math.min(1, p.safeZ))}`);
			out.push(`G1 Z0 F${f(p.plungeRate)}`);
			let zPrev = 0;
			if (arcs) out.push("G17");
			levels.forEach((z, li) => {
				const at = (r: number, a: number) =>
					`X${c(h.x + r * Math.cos(a))} Y${c(h.y + r * Math.sin(a))}`;
				const feed = li === 0 ? ` F${f(p.feedrate)}` : "";
				if (arcs) {
					const centre: Pt = h;
					// 1. Helix down in the middle: one full circle that descends to this level.
					const start: Pt = { x: h.x + rh, y: h.y };
					const [h1, h2] = circleMoves(nf, { from: start, centre, z, zFrom: zPrev, cw: false });
					out.push(`${h1}${feed}`, h2);
					// 2. Flat spiral out to the wall: quarter-turn arcs, each reaching a little wider than the last.
					let cur = start;
					if (wall - rh > 1e-6) {
						const revs = Math.max(1, Math.ceil((wall - rh) / step - 1e-9));
						const quarters = 4 * revs;
						const spiral = (k: number): Pt => {
							const a = (Math.PI / 2) * k;
							const r = rh + (wall - rh) * (k / quarters);
							return { x: h.x + r * Math.cos(a), y: h.y + r * Math.sin(a) };
						};
						for (let k = 0; k < quarters; k += 1) {
							// The circle through the spiral's start, middle and end of this quarter turn.
							const to: Pt = k === quarters - 1 ? { x: h.x + wall, y: h.y } : spiral(k + 1);
							out.push(arcMove(nf, { from: cur, centre: circumcentre(cur, spiral(k + 0.5), to), to, cw: false }));
							cur = to;
						}
					}
					// 3. One full circle on the wall.
					out.push(...circleMoves(nf, { from: cur, centre, cw: false }));
				} else {
					// 1. Helix down in the middle (one revolution) to this level.
					const nh = segmentsFor(rh);
					for (let k = 1; k <= nh; k += 1) {
						const zk = zPrev + (z - zPrev) * (k / nh);
						out.push(`G1 ${at(rh, (2 * Math.PI * k) / nh)} Z${c(zk)}${li === 0 && k === 1 ? feed : ""}`);
					}
					// 2. Flat spiral out to the wall: radius grows linearly with angle.
					const revs = Math.max(1, Math.ceil((wall - rh) / step - 1e-9));
					const ns = segmentsFor(wall) * revs;
					for (let k = 1; k <= ns; k += 1) {
						const a = (2 * Math.PI * k) / segmentsFor(wall);
						out.push(`G1 ${at(rh + (wall - rh) * (k / ns), a)}`);
					}
					// 3. One full circle on the wall.
					const nw = segmentsFor(wall);
					const a0 = (2 * Math.PI * ns) / nw;
					for (let k = 1; k <= nw; k += 1) {
						out.push(`G1 ${at(wall, a0 + (2 * Math.PI * k) / nw)}`);
					}
				}
				// 4. Back to the middle, ready for the next level.
				if (li < levels.length - 1) out.push(`G1 X${c(h.x + rh)} Y${c(h.y)}`);
				zPrev = z;
			});
		}
		out.push(`G0 Z${c(p.safeZ)}`);
	});

	out.push("M5", "M30");
	return `${out.join("\n")}\n`;
};
