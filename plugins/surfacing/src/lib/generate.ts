/**
 * Surfacing → GRBL G-code.
 *
 * Only G0/G1 straight moves (no arcs, no canned cycles). The centre of the bit
 * travels over the whole area, so the area is cleared right up to its edges.
 *
 * Work zero: X0 Y0 is the chosen corner of the area, or its centre (by default the
 * corner the first pass starts at), Z0 is the top of the stock.
 *
 * Passes run along one axis and step over across the other, starting at the
 * chosen corner. Each depth level repeats the whole pattern:
 *  - turn "outside": passes run a bit more than a bit diameter past the edges, so
 *    the sideways step happens in the air (the first plunge is in the air too);
 *  - turn "inside": passes stop on the edge and the step is cut along the edge.
 *  - pattern "snake": every pass runs back the way the last one came, joined by the step;
 *  - pattern "same": after each pass the bit lifts and returns, so all passes cut the same way.
 */

import { comment, fmt } from "@shared/gcode";
import { originOffset, POSITION_NAMES } from "@shared/position";
import { MM_PER_INCH } from "@shared/units";

import { describeStart, type Params } from "./params";

export type Point = { x: number; y: number };

/** How far past the edge an "outside" pass goes, as a multiple of the tool diameter. */
export const OVERSHOOT = 1.1;

/** Cumulative depths for each cutting level, ending exactly at `depth`. */
export const zLevels = (depth: number, stepdown: number): number[] => {
	const n = Math.max(1, Math.ceil(depth / stepdown - 1e-9));
	return Array.from({ length: n }, (_, i) => -Math.min(depth, (i + 1) * (depth / n)));
};

/** Across-the-passes positions from 0 to `span`, evenly spaced, none further apart than the stepover. */
export const passPositions = (span: number, toolDiameter: number, stepover: number): number[] => {
	const step = toolDiameter * stepover;
	const n = Math.max(1, Math.ceil(span / step - 1e-9));
	return Array.from({ length: n + 1 }, (_, i) => (span * i) / n);
};

/** Moves a point from area coordinates (0,0 at the lower-left corner) to machine coordinates. */
export const toMachine = (p: Params, pt: Point): Point => {
	const o = originOffset(p.origin, p.width, p.height);
	return { x: pt.x - o.x, y: pt.y - o.y };
};

/**
 * Pass-axis position `u` (0 at the start edge) and across position `v` (0 at the
 * first pass) to machine X/Y, for the chosen corner and direction.
 */
export const mapPoint = (p: Params, u: number, v: number): Point => {
	const fromRight = p.startX === "right";
	const fromTop = p.startY === "top";
	if (p.passAxis === "x") {
		return { x: fromRight ? p.width - u : u, y: fromTop ? p.height - v : v };
	}
	return { x: fromRight ? p.width - v : v, y: fromTop ? p.height - u : u };
};

export const generateGcode = (p: Params): string => {
	const inch = p.units === "in";
	const scale = inch ? 1 / MM_PER_INCH : 1;
	const dec = inch ? 4 : 3;
	const c = (v: number) => fmt(v * scale, dec);
	const f = (v: number) => fmt(v * scale, inch ? 2 : 0);

	const along = p.passAxis === "x" ? p.width : p.height;
	const across = p.passAxis === "x" ? p.height : p.width;
	const vs = passPositions(across, p.toolDiameter, p.stepover);
	const levels = zLevels(p.depth, p.stepdown);
	const ext = p.turn === "outside" ? p.toolDiameter * OVERSHOOT : 0;
	const uStart = -ext;
	const uEnd = along + ext;
	const clearance = Math.min(1, p.safeZ);
	const xy = (u: number, v: number) => {
		const pt = toMachine(p, mapPoint(p, u, v));
		return `X${c(pt.x)} Y${c(pt.y)}`;
	};

	const out: string[] = [];
	out.push(comment("Generated by Surfacing - gSender plugin"));
	out.push(comment(`Units: ${p.units}`));
	out.push(comment(`Area: ${fmt(p.width, 3)} x ${fmt(p.height, 3)} mm, depth ${fmt(p.depth, 3)} mm in ${levels.length} level(s)`));
	out.push(comment(`Tool: endmill ${fmt(p.toolDiameter, 3)} mm, stepover ${fmt(p.toolDiameter * p.stepover, 3)} mm, ${vs.length} passes per level`));
	out.push(comment(describeStart(p)));
	out.push(comment(`Turns: ${p.turn === "outside" ? "outside the material" : "inside the material"}, ${p.pattern === "snake" ? "back and forth" : "all passes the same direction"}`));
	out.push(comment(`Feeds: cut ${fmt(p.feedrate, 0)}, plunge ${fmt(p.plungeRate, 0)} mm/min, spindle ${fmt(p.spindleRpm, 0)} RPM`));
	out.push(comment(`Work zero: ${POSITION_NAMES[p.origin]} of the area (X0 Y0), Z0 = top of stock`));

	out.push(inch ? "G20" : "G21", "G90", "G17", "G94");
	out.push(`M3 S${fmt(p.spindleRpm, 0)}`);
	if (p.spindleDwell > 0) out.push(`G4 P${fmt(p.spindleDwell, 2)}`);
	out.push(`G0 Z${c(p.safeZ)}`);

	let zPrev = 0;
	levels.forEach((z, li) => {
		out.push(comment(`Level ${li + 1} of ${levels.length}, Z${c(z)}`));
		// Rapid down to just above the surface left by the previous level, then plunge.
		const plunge = (u: number, v: number) => {
			out.push(`G0 ${xy(u, v)}`);
			out.push(`G0 Z${c(Math.min(clearance, zPrev + 1))}`);
			out.push(`G1 Z${c(z)} F${f(p.plungeRate)}`);
		};
		out.push(`G0 Z${c(clearance)}`);
		plunge(uStart, vs[0]);
		let cutFeed = false;
		vs.forEach((v, i) => {
			const forward = p.pattern === "same" || i % 2 === 0;
			const end = forward ? uEnd : uStart;
			out.push(`G1 ${xy(end, v)}${cutFeed ? "" : ` F${f(p.feedrate)}`}`);
			cutFeed = true;
			if (i === vs.length - 1) return;
			if (p.pattern === "snake") {
				// The step across, straight, outside or along the edge.
				out.push(`G1 ${xy(end, vs[i + 1])}`);
			} else {
				out.push(`G0 Z${c(clearance)}`);
				plunge(uStart, vs[i + 1]);
				cutFeed = false;
			}
		});
		zPrev = z;
	});

	out.push(`G0 Z${c(p.safeZ)}`, "M5", "M30");
	return `${out.join("\n")}\n`;
};
