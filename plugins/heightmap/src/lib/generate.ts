/**
 * Height Map plan → GRBL G-code.
 *
 * Only G0/G1 straight moves (no arcs, no canned cycles). Work zero: X0 Y0 is the chosen corner of
 * the picture's rectangle, or its centre; Z0 is the top of the stock.
 *
 * Passes go from shallow to deep (see the shared clearing writer): the bit travels at a small height
 * above the stock, drops to just above the floor the last pass left and ramps in along the stroke.
 */

import { writeClearing } from "@shared/clearing";
import { comment, fmt } from "@shared/gcode";
import { originOffset, POSITION_NAMES } from "@shared/position";
import { MM_PER_INCH } from "@shared/units";

import type { Plan } from "./heightmap";
import { levelDepths, type Params } from "./params";

export const generateGcode = (p: Params, plan: Plan, description: string): string => {
	const inch = p.units === "in";
	const scale = inch ? 1 / MM_PER_INCH : 1;
	const dec = inch ? 4 : 3;
	const c = (v: number) => fmt(v * scale, dec);
	const f = (v: number) => fmt(v * scale, inch ? 2 : 0);
	const o = originOffset(p.origin, plan.width, plan.height);
	const levels = levelDepths(p.depth, p.steps);

	const out: string[] = [];
	out.push(comment("Generated by Height Map - gSender plugin"));
	out.push(comment(`Units: ${p.units}`));
	out.push(comment(`Picture: ${description}, ${fmt(plan.width, 2)} x ${fmt(plan.height, 2)} mm${p.invert ? ", inverted (light = deep)" : ", dark = deep"}`));
	out.push(comment(`Levels: ${levels.map((d) => `-${fmt(d, 3)}`).join(" / ")} mm (${p.steps} step${p.steps === 1 ? "" : "s"} down)`));
	out.push(comment(`Tool: endmill ${fmt(p.toolDiameter, 3)} mm, stepover ${fmt(p.toolDiameter * p.stepover, 3)} mm, ${plan.passes.length} pass(es) of at most ${fmt(p.stepdown, 3)} mm`));
	out.push(comment(`Feeds: cut ${fmt(p.feedrate, 0)}, plunge ${fmt(p.plungeRate, 0)} mm/min, spindle ${fmt(p.spindleRpm, 0)} RPM`));
	out.push(comment(`Work zero: ${POSITION_NAMES[p.origin]} of the picture (X0 Y0), Z0 = top of stock`));

	out.push(inch ? "G20" : "G21", "G90", "G17", "G94");
	out.push(`M3 S${fmt(p.spindleRpm, 0)}`);
	if (p.spindleDwell > 0) out.push(`G4 P${fmt(p.spindleDwell, 2)}`);
	out.push(`G0 Z${c(p.safeZ)}`);

	writeClearing(out, plan.passes, {
		c,
		f,
		toMachine: (pt) => ({ x: pt.x - o.x, y: pt.y - o.y }),
		clearance: Math.min(1, p.safeZ),
		feedrate: p.feedrate,
		plungeRate: p.plungeRate,
		toolDiameter: p.toolDiameter,
	});

	out.push(`G0 Z${c(p.safeZ)}`, "M5", "M30");
	return `${out.join("\n")}\n`;
};
